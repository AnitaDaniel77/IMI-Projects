public class Variables {
    public static void main(String[] args) {

        int myNumber = 88; // Declares an integer variable named myNumber and assigns it the value 88

        short myShort = 32767; // Declares a short variable named myShort and assigns it the value 32767

        long myLong = 9223372036854775807L; // Declares a long variable named myLong and assigns it the value 9223372036854775807

        double myDouble = 3.14159; // Declares a double variable named myDouble and assigns it the value 3.14159

        float myFloat = 3.14f; // Declares a float variable named myFloat and assigns it the value 3.14

        char myChar = 'A'; // Declares a char variable named myChar and assigns it the value 'A'

        boolean myBoolean = true; // Declares a boolean variable named myBoolean and assigns it the value true

        byte myByte = 127; // Declares a byte variable named myByte and assigns it the value 127

        // print each variable to the console
        System.out.println("Integer: " + myNumber);
        System.out.println("Short: " + myShort);
        System.out.println("Long: " + myLong);
        System.out.println("Double: " + myDouble);
        System.out.println("Float: " + myFloat);
        System.out.println("Char: " + myChar);
        System.out.println("Boolean: " + myBoolean);
        System.out.println("Byte: " + myByte);

    }
}
